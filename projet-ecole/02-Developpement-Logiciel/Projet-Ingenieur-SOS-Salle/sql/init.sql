/*Tables secondaires*/

DROP TABLE IF EXISTS LIENS_GROUPES;
DROP TABLE IF EXISTS LIENS_SALLES;
DROP TABLE IF EXISTS GROUPE_cours;
DROP TABLE IF EXISTS SALLE_cours;
DROP TABLE IF EXISTS ENSEIGNANT_cours;
DROP TABLE IF EXISTS JOURNAL_cours;
DROP TABLE IF EXISTS JOURNAL_LIEN;

/*Tables principales*/

DROP TABLE IF EXISTS LIEN_ADE CASCADE;
DROP TABLE IF EXISTS GROUPE CASCADE;
DROP TABLE IF EXISTS cours CASCADE;
DROP TABLE IF EXISTS SALLE CASCADE;
DROP TABLE IF EXISTS ENSEIGNANT CASCADE;
DROP TABLE IF EXISTS JOURNAL_SYNCHRONISATION CASCADE;

/*Tables principales*/

CREATE TABLE LIEN_ADE(
    ID SERIAL PRIMARY KEY,
    LIEN VARCHAR(1024),
    DATE_CREATION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DATE_MODIF TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE GROUPE(
    ID SERIAL PRIMARY KEY,
    NOM VARCHAR(256) NOT NULL,
    IS_SUPER_GROUP BOOLEAN DEFAULT FALSE,
    ACTIF BOOLEAN NOT NULL DEFAULT TRUE,
    DATE_CREATION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DATE_MODIF TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE COURS(
    ID SERIAL PRIMARY KEY,
    UID VARCHAR(128) NOT NULL,
    DATE_DEB TIMESTAMP NOT NULL,
    DATE_FIN TIMESTAMP NOT NULL,
    TITRE VARCHAR(128) NOT NULL,
    TEXT_SALLE VARCHAR(512) NOT NULL,
    TEXT_ENSEIGNANT VARCHAR(1024) NOT NULL,
    TYPE_COURS VARCHAR(8),
    DATE_CREATION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DATE_MODIF TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE SALLE(
    ID SERIAL PRIMARY KEY,
    NUM INT NOT NULL,
    BATIMENT CHAR NOT NULL,
    TYPE_SALLE VARCHAR(16),
    CAPACITE INT,
    DATE_CREATION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DATE_MODIF TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ENSEIGNANT(
    ID SERIAL PRIMARY KEY,
    NOM VARCHAR(64) NOT NULL,
    DATE_CREATION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DATE_MODIF TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE JOURNAL_SYNCHRONISATION(
    ID SERIAL PRIMARY KEY,
    MESSAGE_ERROR VARCHAR(2048) NOT NULL,
    TYPE_MODIF VARCHAR(64) NOT NULL,
    DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

/*Tables secondaires*/

CREATE TABLE LIENS_GROUPES(
    LIEN_ID INT,
    CONSTRAINT fk_lien_groupe FOREIGN KEY (LIEN_ID) REFERENCES LIEN_ADE(ID) ON DELETE CASCADE,
    GROUPE_ID INT,
    CONSTRAINT fk_groupe_lien FOREIGN KEY (GROUPE_ID) REFERENCES GROUPE(ID) ON DELETE CASCADE
);

CREATE TABLE LIENS_SALLES(
    LIEN_ID INT,
    CONSTRAINT fk_lien_salle FOREIGN KEY (LIEN_ID) REFERENCES LIEN_ADE(ID) ON DELETE CASCADE,
    SALLE_ID INT,
    CONSTRAINT fk_salle_lien FOREIGN KEY (SALLE_ID) REFERENCES SALLE(ID) ON DELETE CASCADE
);

CREATE TABLE GROUPE_COURS(
    GROUPE_ID INT,
    CONSTRAINT fk_groupe_cours FOREIGN KEY (GROUPE_ID) REFERENCES GROUPE(ID) ON DELETE CASCADE,
    cours_ID INT,
    CONSTRAINT fk_cours_groupe FOREIGN KEY (cours_ID) REFERENCES cours(ID) ON DELETE CASCADE
);

CREATE TABLE SALLE_COURS(
    SALLE_ID INT,
    CONSTRAINT fk_salle_cours FOREIGN KEY (SALLE_ID) REFERENCES SALLE(ID) ON DELETE CASCADE,
    cours_ID INT,
    CONSTRAINT fk_cours_salle FOREIGN KEY (cours_ID) REFERENCES cours(ID) ON DELETE CASCADE
);

CREATE TABLE ENSEIGNANT_COURS(
    ENSEIGNANT_ID INT,
    CONSTRAINT fk_enseignant_cours FOREIGN KEY (enseignant_id) REFERENCES ENSEIGNANT(ID) ON DELETE CASCADE,
    cours_ID INT,
    CONSTRAINT fk_cours_enseignant FOREIGN KEY (cours_ID) REFERENCES cours(ID) ON DELETE CASCADE
);

CREATE TABLE JOURNAL_COURS(
    JOURNAL_ID INT,
    CONSTRAINT fk_journal_cours FOREIGN KEY (JOURNAL_ID) REFERENCES JOURNAL_SYNCHRONISATION(ID) ON DELETE CASCADE,
    cours_ID INT,
    CONSTRAINT fk_cours_journal FOREIGN KEY (cours_ID) REFERENCES cours(ID) ON DELETE CASCADE
);

CREATE TABLE JOURNAL_LIEN(
    JOURNAL_ID INT,
    CONSTRAINT fk_journal_lien FOREIGN KEY (JOURNAL_ID) REFERENCES JOURNAL_SYNCHRONISATION(ID) ON DELETE CASCADE,
    LIEN_ID INT,
    CONSTRAINT fk_lien_journal FOREIGN KEY (LIEN_ID) REFERENCES LIEN_ADE(ID) ON DELETE CASCADE
);

/****************

    TRIGGERS
    
*****************/

CREATE OR REPLACE FUNCTION update_date_modif_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.DATE_MODIF = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Pour la table GROUPE
DROP TRIGGER IF EXISTS trg_update_date_modif_groupe ON GROUPE;
CREATE TRIGGER trg_update_date_modif_groupe
    BEFORE UPDATE ON GROUPE
    FOR EACH ROW
    EXECUTE FUNCTION update_date_modif_column();

-- Pour la table LIEN_ADE
DROP TRIGGER IF EXISTS trg_update_date_modif_lien_ade ON LIEN_ADE;
CREATE TRIGGER trg_update_date_modif_lien_ade
    BEFORE UPDATE ON LIEN_ADE
    FOR EACH ROW
    EXECUTE FUNCTION update_date_modif_column();

-- Pour la table SALLE
DROP TRIGGER IF EXISTS trg_update_date_modif_salle ON SALLE;
CREATE TRIGGER trg_update_date_modif_salle
    BEFORE UPDATE ON SALLE
    FOR EACH ROW
    EXECUTE FUNCTION update_date_modif_column();

-- Pour la table ENSEIGNANT
DROP TRIGGER IF EXISTS trg_update_date_modif_enseignant ON ENSEIGNANT;
CREATE TRIGGER trg_update_date_modif_enseignant
    BEFORE UPDATE ON ENSEIGNANT
    FOR EACH ROW
    EXECUTE FUNCTION update_date_modif_column();

-- Pour la table cours
DROP TRIGGER IF EXISTS trg_update_date_modif_cours ON cours;
CREATE TRIGGER trg_update_date_modif_cours
    BEFORE UPDATE ON cours
    FOR EACH ROW
    EXECUTE FUNCTION update_date_modif_column();